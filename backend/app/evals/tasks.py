"""Eval cases, derived from the seed challenges so ground truth is never invented.

Three tasks, each mapping onto a capability Sanskritam actually needs:

generate   English prompt + required features -> Sanskrit sentence.
           "Can this model author content at all?"
diagnose   A learner attempt (sometimes correct, sometimes corrupted in exactly
           one known way) -> which word is wrong and what it should be.
           "Can this model teach?" — and, via the control cases, "does it
           falsely accuse correct answers?"
translate  Sanskrit -> English, scored against the seed's own prompt_l1.
           A cheap sanity baseline comparable to published Sanskrit MT results.

Corruptions are generated by re-inflecting a gold stem through the analyzer's
own paradigm tables and then re-analyzing the result: a corruption is only kept
if it parses back to the wrong feature we intended. That keeps the "wrong
answer" wrong in exactly one way, which is what makes diagnose scorable.
"""

from __future__ import annotations

import zlib
from dataclasses import dataclass, field
from typing import Iterable, Optional

from app.grading.analyzer import (
    A_STEM_FEM,
    A_STEM_MASC,
    A_STEM_NEUT,
    I_STEM_MASC,
    NOUN_GENDER,
    analyze_sentence,
    iast_to_devanagari,
)
from app.seeds.challenges import SEED_CHALLENGES


# ─── Case ───

@dataclass
class EvalCase:
    id: str
    task: str                       # generate | diagnose | translate
    system: str
    user: str
    gold: dict                      # task-specific expected data
    meta: dict = field(default_factory=dict)
    json_mode: bool = True


# ─── Shared prompt framing ───
#
# Deliberately register-neutral and short. A long prompt would let a stronger
# instruction-follower win on prompt-reading rather than on Sanskrit, which is
# the thing being measured.

_FEATURE_LEGEND = (
    "Feature codes: cases NOM/ACC/INSTR/DAT/ABL/GEN/LOC/VOC, "
    "numbers SG/DU/PL, tenses PRES/IMPF/FUT/IMP/OPT. "
    "A noun feature looks like ACC.SG; a verb feature looks like PRES.3SG."
)

GENERATE_SYSTEM = (
    "You write correct classical Sanskrit for a language-learning app. "
    "Given an English sentence and the grammatical features it must exercise, "
    "produce ONE Sanskrit sentence in Devanagari that means the English and uses "
    "exactly those features. Prefer simple laukika (spoken) style. "
    + _FEATURE_LEGEND +
    ' Reply with JSON only: {"sanskrit": "<Devanagari sentence>"}'
)

DIAGNOSE_SYSTEM = (
    "You are a Sanskrit tutor grading one learner answer. "
    "You are given the English meaning the learner was asked to express and the "
    "Sanskrit they wrote. Decide whether the Sanskrit is grammatically correct. "
    "If it is correct, say so. If exactly one word carries a wrong inflection, "
    "name that word and the feature it should have had. "
    "Be careful: Sanskrit has free word order, so word order is NEVER an error. "
    + _FEATURE_LEGEND +
    ' Reply with JSON only: {"correct": true|false, "word": "<the wrong word in '
    'the learner text, or empty if correct>", "expected_feature": "<e.g. ACC.SG, '
    'or empty if correct>", "explanation": "<one short sentence>"}'
)

TRANSLATE_SYSTEM = (
    "You translate Sanskrit into plain English for a language-learning app. "
    "Translate the sentence literally and simply. Do not add commentary. "
    'Reply with JSON only: {"english": "<translation>"}'
)


# ─── Corruption machinery (diagnose task) ───

_PARADIGMS: dict[str, list[tuple[str, str, str]]] = {
    "masc": A_STEM_MASC,
    "neut": A_STEM_NEUT,
    "fem": A_STEM_FEM,
}

# Internal sandhi (ṇatva) retroflexes a dental n after r/ṛ/ṣ earlier in the word:
# rāma + ena -> rāmeṇa, not *rāmena. Naive concatenation would silently produce a
# second, unintended error, so endings containing a dental n are skipped for such
# stems. The eval needs each corruption wrong in exactly ONE way.
_NATVA_TRIGGERS = ("r", "ṛ", "ṣ")


def _violates_natva(base: str, ending: str) -> bool:
    return "n" in ending and any(t in base for t in _NATVA_TRIGGERS)


def _inflect(base: str, ending: str) -> str:
    return base + ending


def _noun_corruptions(word: str, stem: str, gold_feature: str) -> list[tuple[str, str]]:
    """Return [(corrupted_word, wrong_feature)] for one gold noun.

    Only emits a corruption when re-analyzing the produced form yields exactly
    the wrong feature intended — so a corruption can never be accidentally right.
    """
    gender = NOUN_GENDER.get(stem)
    tables: list[tuple[str, str, str]] = []
    if gender in _PARADIGMS:
        tables = _PARADIGMS[gender]
    elif stem.endswith("i"):
        tables = I_STEM_MASC
    if not tables:
        return []

    # Recover the consonantal base by dropping the stem vowel the table declares.
    out: list[tuple[str, str]] = []
    seen: set[str] = set()
    for ending, feature, stem_vowel in tables:
        if feature == gold_feature:
            continue
        if not stem.endswith(stem_vowel):
            continue
        base = stem[: -len(stem_vowel)]
        if _violates_natva(base, ending):
            continue
        candidate = _inflect(base, ending)
        if candidate == word or candidate in seen:
            continue

        # Verify: the corrupted form must analyze back to the wrong feature,
        # unambiguously (no alternative reading that equals the gold feature,
        # which would make the "error" actually correct).
        results = analyze_sentence(candidate)
        if len(results) != 1 or not results[0].is_confident:
            continue
        readings = [results[0].parsed] + list(results[0].alternatives)
        feats = {f for r in readings for f in r.values()}
        if gold_feature in feats or feature not in feats:
            continue

        seen.add(candidate)
        out.append((candidate, feature))
    return out


def _iast_words(target_iast: str) -> list[str]:
    return [w.strip("।॥,.!?") for w in target_iast.split() if w.strip("।॥,.!?")]


def build_corruption(challenge: dict) -> Optional[dict]:
    """Corrupt exactly one noun in a seed challenge.

    Returns {"text", "word", "gold_feature", "wrong_feature", "role"} or None
    when no verifiable single-error corruption exists for this challenge.

    Every valid corruption is enumerated first, then one is chosen by a stable
    hash of the sentence. Taking the first candidate instead would make almost
    every case a NOM.SG -> NOM.DU error on the first word, which a model could
    score well on without reading the Sanskrit at all.
    """
    accepted = (challenge.get("accepted_parses") or [{}])[0]
    words = _iast_words(challenge.get("target_iast", ""))
    if not accepted or not words:
        return None

    candidates: list[dict] = []
    for idx, word in enumerate(words):
        results = analyze_sentence(word)
        if len(results) != 1 or not results[0].is_confident:
            continue
        for role, feature in results[0].parsed.items():
            # Nouns only: verb stems undergo lengthening (khāda -> khādāmi) that
            # plain concatenation cannot model, so verb corruptions are not safe.
            if role.startswith("√") or "." not in feature:
                continue
            if feature.split(".")[0] not in (
                "NOM", "ACC", "INSTR", "DAT", "ABL", "GEN", "LOC", "VOC"
            ):
                continue
            if accepted.get(role) != feature:
                continue
            for corrupted, wrong_feature in _noun_corruptions(word, role, feature):
                new_words = list(words)
                new_words[idx] = corrupted
                candidates.append({
                    "text": " ".join(new_words),
                    "word": corrupted,
                    "role": role,
                    "gold_feature": feature,
                    "wrong_feature": wrong_feature,
                })

    if not candidates:
        return None
    # crc32, not hash(): str hashing is salted per-process, and eval cases must
    # be identical across runs and machines for results to be comparable.
    seed = zlib.crc32(challenge.get("target_iast", "").encode("utf-8"))
    return candidates[seed % len(candidates)]


# ─── Builders ───

def _cid(prefix: str, i: int) -> str:
    return f"{prefix}-{i:03d}"


def build_generate_cases(challenges: Iterable[dict]) -> list[EvalCase]:
    cases = []
    for i, ch in enumerate(challenges):
        features = ch.get("features") or []
        if not features:
            continue
        cases.append(EvalCase(
            id=_cid("gen", i),
            task="generate",
            system=GENERATE_SYSTEM,
            user=(
                f"English: {ch['prompt_l1']}\n"
                f"Required features: {', '.join(features)}"
            ),
            gold={
                "features": features,
                "accepted_parses": ch.get("accepted_parses") or [],
                "reference_iast": ch.get("target_iast", ""),
                "reference_devanagari": ch.get("target_sanskrit", ""),
            },
            meta={"register": ch.get("register", "laukika"), "prompt_l1": ch["prompt_l1"]},
        ))
    return cases


def build_diagnose_cases(challenges: Iterable[dict]) -> list[EvalCase]:
    """One corrupted case per challenge where a corruption is derivable, plus a
    matching control case using the untouched correct sentence.

    The controls are not padding — they measure false-accusation rate, which for
    a teaching product matters more than catching every real error.
    """
    cases: list[EvalCase] = []
    for i, ch in enumerate(challenges):
        # Control: the correct sentence. The model must NOT flag it.
        cases.append(EvalCase(
            id=_cid("diag-ok", i),
            task="diagnose",
            system=DIAGNOSE_SYSTEM,
            user=(
                f"English meaning: {ch['prompt_l1']}\n"
                f"Learner wrote: {ch['target_sanskrit']}"
            ),
            gold={"correct": True},
            meta={"kind": "control", "register": ch.get("register", "laukika")},
        ))

        corruption = build_corruption(ch)
        if corruption is None:
            continue
        cases.append(EvalCase(
            id=_cid("diag-err", i),
            task="diagnose",
            system=DIAGNOSE_SYSTEM,
            user=(
                f"English meaning: {ch['prompt_l1']}\n"
                f"Learner wrote: {iast_to_devanagari(corruption['text'])}"
            ),
            gold={
                "correct": False,
                "word_iast": corruption["word"],
                "word_devanagari": iast_to_devanagari(corruption["word"]),
                "expected_feature": corruption["gold_feature"],
                "wrong_feature": corruption["wrong_feature"],
                "role": corruption["role"],
            },
            meta={"kind": "error", "register": ch.get("register", "laukika")},
        ))
    return cases


def build_translate_cases(challenges: Iterable[dict]) -> list[EvalCase]:
    cases = []
    for i, ch in enumerate(challenges):
        if not ch.get("target_sanskrit"):
            continue
        cases.append(EvalCase(
            id=_cid("tr", i),
            task="translate",
            system=TRANSLATE_SYSTEM,
            user=f"Sanskrit: {ch['target_sanskrit']}",
            gold={"english": ch["prompt_l1"]},
            meta={"register": ch.get("register", "laukika")},
        ))
    return cases


TASK_BUILDERS = {
    "generate": build_generate_cases,
    "diagnose": build_diagnose_cases,
    "translate": build_translate_cases,
}


def build_cases(tasks: Iterable[str], challenges: Optional[list[dict]] = None,
                limit: Optional[int] = None) -> list[EvalCase]:
    """Build all cases for the named tasks. `limit` caps challenges, not cases."""
    source = list(challenges if challenges is not None else SEED_CHALLENGES)
    if limit:
        source = source[:limit]
    cases: list[EvalCase] = []
    for task in tasks:
        builder = TASK_BUILDERS.get(task)
        if builder is None:
            raise ValueError(
                f"Unknown task {task!r}. Known: {', '.join(TASK_BUILDERS)}"
            )
        cases.extend(builder(source))
    return cases
